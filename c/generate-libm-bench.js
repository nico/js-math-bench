#!/usr/bin/env node
// Generates bench-libm-data.inc containing test data arrays and DATA_* macros.
// Usage: node generate-libm-bench.js > bench-libm-data.inc

'use strict';

const fs = require('fs');
const path = require('path');

const testData = JSON.parse(
  fs.readFileSync(path.join(__dirname, '..', 'test_data.json'), 'utf8')
);

const BINARY_FUNCTIONS = new Set(['atan2', 'hypot', 'pow']);
const ALL_FUNCTIONS = [
  'acos', 'acosh', 'asin', 'asinh', 'atan', 'atan2', 'atanh',
  'cbrt', 'cos', 'cosh', 'exp', 'expm1', 'hypot', 'log', 'log1p', 'log2', 'log10',
  'pow', 'sin', 'sinh', 'sqrt', 'tan', 'tanh'
];

// Convert test data values to valid C literals.
function toCLiteral(s) {
  if (s === 'NaN') return 'NAN';
  if (s === '+Infinity' || s === 'Infinity') return 'INFINITY';
  if (s === '-Infinity') return '-INFINITY';
  if (s === '0') return '0.0';
  if (s === '-0') return '-0.0';
  return s;  // hex floats like "0x1.921fb54442d18p+1" are valid C
}

let out = '// Auto-generated by generate-libm-bench.js -- do not edit\n\n';

for (const fnName of ALL_FUNCTIONS) {
  const fd = testData[fnName];
  if (!fd) continue;
  const isBinary = BINARY_FUNCTIONS.has(fnName);
  const categories = ['worstCase', 'systematic', 'edgeCases'];
  const macroLines = [];

  for (const cat of categories) {
    const cases = fd[cat] || [];
    if (cases.length === 0) continue;

    if (isBinary) {
      out += `static const double testdata_${fnName}_${cat}_a[] = {\n`;
      out += cases.map(tc => '  ' + toCLiteral(tc.in[0])).join(',\n');
      out += '\n};\n';
      out += `static const double testdata_${fnName}_${cat}_b[] = {\n`;
      out += cases.map(tc => '  ' + toCLiteral(tc.in[1])).join(',\n');
      out += '\n};\n';
    } else {
      out += `static const double testdata_${fnName}_${cat}_in[] = {\n`;
      out += cases.map(tc => '  ' + toCLiteral(tc.in)).join(',\n');
      out += '\n};\n';
    }
    out += `static const double testdata_${fnName}_${cat}_out[] = {\n`;
    out += cases.map(tc => '  ' + toCLiteral(tc.out)).join(',\n');
    out += '\n};\n\n';

    // V(name, cat, n, in_arr, out_arr, a_arr, b_arr)
    if (isBinary) {
      macroLines.push(
        `    V(name, ${cat}, ${cases.length}, _,` +
        ` testdata_${fnName}_${cat}_out,` +
        ` testdata_${fnName}_${cat}_a,` +
        ` testdata_${fnName}_${cat}_b)`
      );
    } else {
      macroLines.push(
        `    V(name, ${cat}, ${cases.length},` +
        ` testdata_${fnName}_${cat}_in,` +
        ` testdata_${fnName}_${cat}_out, _, _)`
      );
    }
  }

  out += `#define DATA_${fnName}(V, name) \\\n`;
  out += macroLines.join(' \\\n') + '\n\n';
}

process.stdout.write(out);
